    private final String[] rows;
    private final Paint p = new Paint();
    private final int size;

    QrView(Context c, String[] rows) {
        super(c);
        this.rows = rows;
        size = Math.round(c.getResources().getDisplayMetrics().density * 224);
        setMinimumWidth(size); setMinimumHeight(size);
    }

    @Override protected void onMeasure(int w, int h) { setMeasuredDimension(size, size); }

    @Override protected void onDraw(Canvas c) {
        c.drawColor(Color.WHITE); // белая подложка и «тихая зона» нужны сканеру при любой теме приложения
        int n = rows.length;
        float m = size / (float) (n + 8); // 4 модуля тихой зоны с каждой стороны
        p.setColor(Color.BLACK);
        for (int r = 0; r < n; r++) {
            String s = rows[r];
            for (int q = 0; q < n; q++) if (s.charAt(q) == '1') c.drawRect((q + 4) * m, (r + 4) * m, (q + 5) * m + 0.5f, (r + 5) * m + 0.5f, p);
        }
    }
